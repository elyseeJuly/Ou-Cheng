for (const [s, t] of Object.entries(S2T_MAP)) {
  T2S_MAP[t] = s;
}

/**
 * 将文本转为简体表达
 */
export function toSimplified(text: string): string {
  if (!text) return '';
  return Array.from(text).map(char => T2S_MAP[char] || char).join('');
}

/**
 * 将文本转为繁体表达
 */
export function toTraditional(text: string): string {
  if (!text) return '';
  return Array.from(text).map(char => S2T_MAP[char] || char).join('');
}

/**
 * 简繁通搜匹配算法：
 * 支持无论用户输入简体还是繁体，均可匹配原文中的繁简内容
 */
export function matchesSearch(source: string | undefined, query: string): boolean {
  if (!query) return true;
  if (!source) return false;

  const cleanQuery = query.trim().toLowerCase();
  if (!cleanQuery) return true;

  const cleanSource = source.toLowerCase();

  // 1. 原文字符串包含
  if (cleanSource.includes(cleanQuery)) return true;

  // 2. 统一转为简体后比较
  const simSource = toSimplified(cleanSource);
  const simQuery = toSimplified(cleanQuery);
  if (simSource.includes(simQuery)) return true;

  // 3. 统一转为繁体后比较
  const tradSource = toTraditional(cleanSource);
  const tradQuery = toTraditional(cleanQuery);
  if (tradSource.includes(tradQuery)) return true;

  return false;
}
